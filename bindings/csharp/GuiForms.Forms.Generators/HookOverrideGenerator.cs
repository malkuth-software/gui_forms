// Registers, per compiled assembly, every class's overrides of the generated
// OnX virtuals ([GuiForms.Forms.Hook] methods): a module initializer calls
// ClassOverrides.register(typeof(Class), keys) once per class, before any of
// the assembly's code runs. ClassTables then fills only those entries, so a
// hook the program does not override stays null in its class table.
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace GuiForms.Forms.Generators;

/// <summary>One override: its class and the hook's segment entry.</summary>
internal readonly struct HookOverride : System.IEquatable<HookOverride>
{
    public readonly string type_name;
    public readonly uint class_id;
    public readonly uint entry;

    public HookOverride(string type_name, uint class_id, uint entry)
    {
        this.type_name = type_name;
        this.class_id = class_id;
        this.entry = entry;
    }

    public bool Equals(HookOverride other)
    {
        return type_name == other.type_name && class_id == other.class_id && entry == other.entry;
    }

    public override bool Equals(object? other)
    {
        return other is HookOverride found && Equals(found);
    }

    public override int GetHashCode()
    {
        return type_name.GetHashCode() ^ (int)(class_id * 397u) ^ (int)entry;
    }
}

[Generator(LanguageNames.CSharp)]
public sealed class HookOverrideGenerator : IIncrementalGenerator
{
    private const string hook_attribute = "GuiForms.Forms.HookAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<HookOverride?> found =
            context.SyntaxProvider.CreateSyntaxProvider(is_override, read_override);
        IncrementalValueProvider<ImmutableArray<HookOverride?>> collected = found.Collect();
        context.RegisterSourceOutput(collected, emit);
    }

    private static bool is_override(SyntaxNode node, CancellationToken cancellation)
    {
        if (node is not MethodDeclarationSyntax method)
        {
            return false;
        }
        foreach (SyntaxToken modifier in method.Modifiers)
        {
            if (modifier.IsKind(SyntaxKind.OverrideKeyword))
            {
                return true;
            }
        }
        return false;
    }

    // The hook the override overrides, null when it overrides no [Hook] virtual.
    private static HookOverride? read_override(GeneratorSyntaxContext context, CancellationToken cancellation)
    {
        if (context.SemanticModel.GetDeclaredSymbol(context.Node, cancellation) is not IMethodSymbol method)
        {
            return null;
        }
        IMethodSymbol? overridden = method.OverriddenMethod;
        while (overridden != null)
        {
            foreach (AttributeData attribute in overridden.GetAttributes())
            {
                if (attribute.AttributeClass?.ToDisplayString() != hook_attribute ||
                    attribute.ConstructorArguments.Length != 2)
                {
                    continue;
                }
                object? class_id = attribute.ConstructorArguments[0].Value;
                object? entry = attribute.ConstructorArguments[1].Value;
                if (class_id is uint class_value && entry is uint entry_value)
                {
                    string type_name = method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    return new HookOverride(type_name, class_value, entry_value);
                }
            }
            overridden = overridden.OverriddenMethod;
        }
        return null;
    }

    private static void emit(SourceProductionContext context, ImmutableArray<HookOverride?> overrides)
    {
        SortedDictionary<string, SortedSet<ulong>> by_type = new SortedDictionary<string, SortedSet<ulong>>();
        foreach (HookOverride? candidate in overrides)
        {
            if (candidate is not HookOverride found)
            {
                continue;
            }
            if (!by_type.TryGetValue(found.type_name, out SortedSet<ulong>? keys))
            {
                keys = new SortedSet<ulong>();
                by_type.Add(found.type_name, keys);
            }
            keys.Add(((ulong)found.class_id << 32) | found.entry);
        }
        if (by_type.Count == 0)
        {
            return;
        }
        StringBuilder text = new StringBuilder();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("namespace GuiForms.Forms.Generated;");
        text.AppendLine();
        text.AppendLine("internal static class HookOverrideRegistration");
        text.AppendLine("{");
        text.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        text.AppendLine("    internal static void register()");
        text.AppendLine("    {");
        foreach (KeyValuePair<string, SortedSet<ulong>> type in by_type)
        {
            text.Append("        global::GuiForms.Forms.ClassOverrides.register(typeof(").Append(type.Key)
                .AppendLine("), new global::GuiForms.Forms.HookKey[]");
            text.AppendLine("        {");
            foreach (ulong key in type.Value)
            {
                uint class_id = (uint)(key >> 32);
                uint entry = (uint)(key & 0xffffffffu);
                text.Append("            new global::GuiForms.Forms.HookKey(")
                    .Append(class_id.ToString(CultureInfo.InvariantCulture)).Append("u, ")
                    .Append(entry.ToString(CultureInfo.InvariantCulture)).AppendLine("u),");
            }
            text.AppendLine("        });");
        }
        text.AppendLine("    }");
        text.AppendLine("}");
        context.AddSource("HookOverrideRegistration.g.cs", text.ToString());
    }
}
