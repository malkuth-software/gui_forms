// A composite control's C++ generator (cp34, phase 2; control_generator.hpp).

#include "control_generator.hpp"

#include "../../form_language/form_generator/form_generator.hpp"

#include <algorithm>
#include <string_view>
#include <vector>

namespace gui_forms::control_language {

namespace {

using theme_language::DiagnosticCode;
using theme_language::ThemeDiagnostic;

// The raw literal's delimiter, which the document may not hold closed.
constexpr std::string_view raw_delimiter = "gfcontrol";
constexpr std::string_view raw_close = ")gfcontrol\"";
// The base the run-time loader always adds (load_composite_definition).
constexpr std::string_view base_type_name = "user_control";

class ControlGenerator final {
public:
    ControlGenerator(const theme_language::ThemeSource& source, const CompositeDefinition& definition,
                     const ControlGeneratorOptions& options, theme_language::ThemeDiagnosticList& diagnostics) noexcept
        : source_(source), definition_(definition), options_(options), diagnostics_(diagnostics) {}

    [[nodiscard]] ControlGenerateOutcome run(std::string& generated);

private:
    void refuse(std::string_view detail);
    void check();
    void gather_child_types();
    void write_preamble(std::string& out) const;
    void write_class(std::string& out) const;
    void write_accessors(std::string& out) const;

    const theme_language::ThemeSource& source_;
    const CompositeDefinition& definition_;
    const ControlGeneratorOptions& options_;
    theme_language::ThemeDiagnosticList& diagnostics_;
    // The schema indices of the child types, in first use, the base aside.
    std::vector<std::size_t> child_types_{};
    bool refused_{};
};

void ControlGenerator::refuse(const std::string_view detail) {
    ThemeDiagnostic diagnostic{};
    diagnostic.code = DiagnosticCode::form_generation_refused;
    diagnostic.file = std::string(source_.file);
    diagnostic.rule = definition_.name;
    diagnostic.detail = theme_language::clipped_theme_detail(detail);
    diagnostics_.add(std::move(diagnostic));
    refused_ = true;
}

void ControlGenerator::check() {
    if (!form_language::form_identifier(options_.class_name)) refuse("the class name is not an identifier");
    if (!options_.namespace_name.empty() && !form_language::form_qualified_name(options_.namespace_name)) {
        refuse("the namespace is not a qualified name");
    }
    if (source_.text.size() > maximum_embedded_control_bytes) refuse("the document is too large to embed");
    if (source_.text.find(raw_close) != std::string_view::npos) refuse("the document holds )gfcontrol\"");
}

void ControlGenerator::gather_child_types() {
    const std::vector<form_language::FormObject>& objects = definition_.children.objects;
    for (std::size_t index = 1U; index < objects.size(); ++index) {
        const std::size_t type = objects[index].schema_type;
        const form_language::FormSchemaType& described = definition_.schema.types[type];
        if (described.name == base_type_name) continue;
        const bool listed = std::find(child_types_.begin(), child_types_.end(), type) != child_types_.end();
        if (listed) continue;
        if (described.cpp_type.empty() || described.header.empty()) {
            refuse("a child type has no C++ class or header: " + described.name);
            continue;
        }
        child_types_.push_back(type);
    }
}

void ControlGenerator::write_preamble(std::string& out) const {
    out += "// Generated by gui_forms_form_compiler from ";
    out += options_.source_name;
    out += ". Do not edit: change the document and build again.\n";
    out += "#pragma once\n\n";
    out += "#include \"gui_forms/composites/composite_control/composite_control.hpp\"\n";
    std::vector<std::string> headers{};
    for (const std::size_t type : child_types_) headers.push_back(definition_.schema.types[type].header);
    std::sort(headers.begin(), headers.end());
    headers.erase(std::unique(headers.begin(), headers.end()), headers.end());
    for (const std::string& header : headers) {
        out += "#include \"";
        out += header;
        out += "\"\n";
    }
    out += "\n#include <array>\n#include <memory>\n#include <optional>\n#include <stdexcept>\n"
           "#include <string>\n#include <string_view>\n#include <utility>\n#include <variant>\n\n";
}

void ControlGenerator::write_accessors(std::string& out) const {
    for (const CompositePropertyDefinition& property : definition_.properties) {
        if (property.presentational || property.command) continue;
        const std::string& name = property.descriptor.name;
        if (!form_language::form_identifier(name)) continue;
        std::string_view type{};
        std::string_view held{};
        std::string_view fallback{};
        switch (property.kind) {
        case ControlPropertyKind::boolean:
            type = "bool";
            held = "bool";
            fallback = "false";
            break;
        case ControlPropertyKind::number:
            type = "double";
            held = "double";
            fallback = "0.0";
            break;
        case ControlPropertyKind::text:
            type = "std::string";
            held = "std::string";
            fallback = "std::string{}";
            break;
        default:
            // Other kinds are reached through property_value by name.
            break;
        }
        if (type.empty()) continue;
        out += "    // `";
        out += property.name;
        out += "`, as the registered property holds it.\n";
        out += "    [[nodiscard]] ";
        out += type;
        out += " read_";
        out += name;
        out += "() const {\n        const std::optional<gui_forms::BindingValue> value = property_value(\"";
        out += name;
        out += "\");\n        const ";
        out += held;
        out += "* held = value ? std::get_if<";
        out += held;
        out += ">(&*value) : nullptr;\n        if (held == nullptr) return ";
        out += fallback;
        out += ";\n        return *held;\n    }\n";
        out += "    void write_";
        out += name;
        out += "(";
        out += type;
        out += " value) { set_property_value(\"";
        out += name;
        out += "\", gui_forms::BindingValue{std::move(value)}); }\n";
    }
}

void ControlGenerator::write_class(std::string& out) const {
    const std::string& name = options_.class_name;
    out += "// The `";
    out += definition_.name;
    out += "` composite control.\n";
    out += "class ";
    out += name;
    out += " : public gui_forms::CompositeControl {\npublic:\n";
    out += "    // The document, embedded at build time, and the types its children name.\n";
    out += "    static constexpr std::string_view document_name = \"";
    out += options_.source_name;
    out += "\";\n    static constexpr std::string_view document = R\"";
    out += raw_delimiter;
    out += "(";
    out += source_.text;
    out += ")";
    out += raw_delimiter;
    out += "\";\n";
    out += "    static constexpr std::array<gui_forms::CompositeChildType, ";
    out += std::to_string(child_types_.size());
    out += "> child_types{";
    for (std::size_t index = 0U; index < child_types_.size(); ++index) {
        const form_language::FormSchemaType& type = definition_.schema.types[child_types_[index]];
        out += index == 0U ? "\n" : ",\n";
        out += "        gui_forms::composite_child_type<";
        out += type.cpp_type;
        out += ">(\"";
        out += type.name;
        out += "\")";
    }
    out += child_types_.empty() ? "};\n\n" : ",\n    };\n\n";
    out += "    explicit ";
    out += name;
    out += "(gui_forms::StableId stable_id)\n        : gui_forms::CompositeControl(std::move(stable_id), "
           "shared_definition()) {}\n\n";
    out += "    // The definition, loaded on first use and shared by every instance.\n";
    out += "    // std::logic_error when it is refused: the build checked it, so only a\n";
    out += "    // library that differs from the compiler's refuses it.\n";
    out += "    [[nodiscard]] static std::shared_ptr<const gui_forms::CompositeDefinition> shared_definition() {\n";
    out += "        static const std::shared_ptr<const gui_forms::CompositeDefinition> made = load_definition();\n";
    out += "        return made;\n    }\n\n";
    write_accessors(out);
    out += "\nprivate:\n";
    out += "    [[nodiscard]] static std::shared_ptr<const gui_forms::CompositeDefinition> load_definition() {\n";
    out += "        const gui_forms::CompositeLoadResult loaded =\n";
    out += "            gui_forms::load_composite_definition(document_name, document, child_types);\n";
    out += "        if (!loaded) throw std::logic_error(\"";
    out += name;
    out += ": the embedded definition was refused\");\n";
    out += "        return loaded.definition;\n    }\n};\n";
}

ControlGenerateOutcome ControlGenerator::run(std::string& generated) {
    check();
    gather_child_types();
    if (refused_) return ControlGenerateOutcome::refused;
    std::string out{};
    write_preamble(out);
    if (!options_.namespace_name.empty()) {
        out += "namespace ";
        out += options_.namespace_name;
        out += " {\n\n";
    }
    write_class(out);
    if (!options_.namespace_name.empty()) {
        out += "\n} // namespace ";
        out += options_.namespace_name;
        out += "\n";
    }
    generated = std::move(out);
    return ControlGenerateOutcome::generated;
}

} // namespace

ControlGenerateOutcome generate_control_cpp(const theme_language::ThemeSource& source,
                                            const CompositeDefinition& definition,
                                            const ControlGeneratorOptions& options, std::string& generated,
                                            theme_language::ThemeDiagnosticList& diagnostics) {
    ControlGenerator generator(source, definition, options, diagnostics);
    const ControlGenerateOutcome outcome = generator.run(generated);
    return outcome;
}

} // namespace gui_forms::control_language
