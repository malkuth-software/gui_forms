#!/usr/bin/env python3
"""Generates language bindings of the C ABI from its audited manifest.

``manifests/abi/gf_abi.json`` (written by ``tools/abi_audit.py extract``) is
the only input: every type, field offset, slot signature and constant the
bindings carry comes from it, so the bindings cannot drift from the header
without the audit's manifest check failing first.

``python3 tools/abi_bindings.py csharp`` writes the C# interop layer's
generated files under ``bindings/csharp/GuiForms.Interop/Generated/``;
``python3 tools/abi_bindings.py cpp`` writes the header-only C++ wrappers,
``include/gui_forms/c/gf_abi.hpp``. ``--check`` fails when a checked-in file
differs from what the manifest gives, and for the C++ wrappers also when the
slot map is not 1:1 (every wrapper method calls exactly one slot, and every
slot of every table has exactly one wrapper method).

The C++ wrappers: one class per table, made only by negotiation (or by
adopting a table the caller negotiated), with one method per slot of the
slot's own signature. The invariant a method adds is the slot's presence: a
slot the library did not serve (beyond the negotiated struct_size, or null)
answers GF_STATUS_UNSUPPORTED_VERSION instead of calling through null. Two
owners hold the ABI's references: ObjectReference (objects.release) and
SubscriptionReference (events.disconnect).

The C# interop is the 1:1 layer only:

- every scalar typedef is a ``global using`` alias of its fixed-width type
  (``Aliases.g.cs``, which a consumer spelling the C names compiles too);
- every record, extensible record and table is a blittable
  ``LayoutKind.Sequential`` struct whose fields are the C fields in order,
  slots as ``delegate* unmanaged[Cdecl]<...>`` function pointers;
- every constant is a ``const`` of its manifest type;
- ``gf_abi_get_table`` is the one ``[LibraryImport]``, and each table has a
  ``get_<name>_table`` that negotiates it at the manifest's version;
- ``Layout.check`` compares ``sizeof`` and every field offset as the .NET
  runtime lays them out with the manifest's numbers, so a C# build on any host
  proves its own layout.

The ownership, callback and failure layer is hand-written beside it
(``bindings/csharp/GuiForms.Interop/*.cs``); the Forms-shaped API is stage S.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "manifests" / "abi" / "gf_abi.json"
CSHARP_OUTPUT = ROOT / "bindings" / "csharp" / "GuiForms.Interop" / "Generated"
CPP_OUTPUT = ROOT / "include" / "gui_forms" / "c" / "gf_abi.hpp"
CPP_OWNERS = ROOT / "tools" / "abi_bindings_owners.hpp.in"
NAMESPACE = "GuiForms.Interop"

HEADER = "// <auto-generated/>\n// Generated from manifests/abi/gf_abi.json by `python3 tools/abi_bindings.py csharp`. Do not edit.\n"

# The C fixed-width types the dialect admits, as C# keywords.
PRIMITIVES = {
    "uint8_t": "byte",
    "int8_t": "sbyte",
    "uint16_t": "ushort",
    "int16_t": "short",
    "uint32_t": "uint",
    "int32_t": "int",
    "uint64_t": "ulong",
    "int64_t": "long",
    "double": "double",
    "float": "float",
    "char": "byte",
    "void": "void",
}

CONSTANT_TYPES = {"uint32": ("uint", "u"), "uint64": ("ulong", "ul"), "int32": ("int", "")}

KEYWORDS = frozenset(
    "abstract as base bool break byte case catch char checked class const continue decimal default delegate do "
    "double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface "
    "internal is lock long namespace new null object operator out override params private protected public readonly "
    "ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint "
    "ulong unchecked unsafe ushort using virtual void volatile while".split())


class BindingError(Exception):
    """The manifest holds something the generator has no spelling for."""


def identifier(name: str) -> str:
    """A C name as a C# identifier: keywords take the verbatim prefix."""
    if name in KEYWORDS:
        return "@" + name
    return name


def type_name(c_type: str, known: set[str]) -> str:
    """A C type (no arrays, no function slots) as its C# spelling."""
    text = c_type.replace("const ", "").strip()
    stars = 0
    while text.endswith("*"):
        stars += 1
        text = text[:-1].strip()
    if text in PRIMITIVES:
        base = PRIMITIVES[text]
    elif text in known:
        base = text
    else:
        raise BindingError(f"no C# spelling for the C type {c_type!r}")
    if base == "void" and stars == 0:
        return "void"
    return base + "*" * stars


def slot_type(signature: dict, known: set[str]) -> str:
    """A slot's signature as an unmanaged function pointer type."""
    parts = [type_name(parameter["type"], known) for parameter in signature["parameters"]]
    parts.append(type_name(signature["returns"], known))
    return "delegate* unmanaged[Cdecl]<" + ", ".join(parts) + ">"


def array_shape(c_type: str) -> tuple[str, int] | None:
    """(element type, count) of a fixed array field such as uint8_t[32]."""
    if not c_type.endswith("]"):
        return None
    element, _, count = c_type[:-1].partition("[")
    return element.strip(), int(count)


def check_no_overlap(struct: dict) -> None:
    """Sequential layout cannot express a union; the manifest has none today."""
    end = 0
    for field in struct["fields"]:
        if field["offset"] < end:
            raise BindingError(f"{struct['name']}.{field['name']} overlaps the field before it")
        end = field["offset"] + field["size"]


def render_types(manifest: dict) -> str:
    """Scalars as global aliases, then every struct."""
    scalars = manifest["scalars"]
    structs = manifest["structs"]
    known = {scalar["name"] for scalar in scalars} | {struct["name"] for struct in structs}
    lines = [HEADER, "using System.Runtime.InteropServices;", "", f"namespace {NAMESPACE};", ""]
    for struct in structs:
        check_no_overlap(struct)
        lines.append(f"/// <summary>{struct['name']} ({struct['kind']}, {struct['size']} bytes).</summary>")
        lines.append("[StructLayout(LayoutKind.Sequential)]")
        lines.append(f"public unsafe struct {struct['name']}")
        lines.append("{")
        for field in struct["fields"]:
            name = identifier(field["name"])
            shape = array_shape(field["type"])
            if field["type"] == "function":
                lines.append(f"    public {slot_type(field['signature'], known)} {name};")
            elif shape is not None:
                element = type_name(shape[0], known)
                lines.append(f"    public fixed {element} {name}[{shape[1]}];")
            else:
                lines.append(f"    public {type_name(field['type'], known)} {name};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def render_aliases(manifest: dict) -> str:
    """The scalar typedefs as global aliases. An alias is visible only in the
    assembly that compiles it, so a consumer that spells the C names compiles
    this file too (the C# test project does)."""
    lines = [HEADER]
    for scalar in manifest["scalars"]:
        lines.append(f"global using {scalar['name']} = {PRIMITIVES[scalar['type']]};")
    lines.append("")
    return "\n".join(lines)


def render_constants(manifest: dict) -> str:
    lines = [HEADER, f"namespace {NAMESPACE};", "", "/// <summary>The header's constants.</summary>",
             "public static class Constants", "{"]
    for constant in manifest["constants"]:
        spelling, suffix = CONSTANT_TYPES[constant["type"]]
        lines.append(f"    public const {spelling} {constant['name']} = {constant['value']}{suffix};")
    lines += ["}", ""]
    return "\n".join(lines)


def table_ids(manifest: dict) -> list[tuple[str, str]]:
    """(table struct, GF_TABLE_ constant) for every table: gf_X_table <-> GF_TABLE_X."""
    constants = {constant["name"] for constant in manifest["constants"]}
    pairs = []
    for struct in manifest["structs"]:
        if struct["kind"] != "table":
            continue
        stem = struct["name"][len("gf_"):-len("_table")]
        constant = "GF_TABLE_" + stem.upper()
        if constant not in constants:
            raise BindingError(f"{struct['name']} has no {constant}")
        pairs.append((struct["name"], constant))
    return pairs


def render_exports(manifest: dict) -> str:
    known = {scalar["name"] for scalar in manifest["scalars"]} | {struct["name"] for struct in manifest["structs"]}
    lines = [HEADER, "using System.Runtime.CompilerServices;", "using System.Runtime.InteropServices;", "",
             "[assembly: DisableRuntimeMarshalling]", "", f"namespace {NAMESPACE};", "",
             "/// <summary>The library's one export and the negotiation of each table.</summary>",
             "public static unsafe partial class Exports", "{",
             "    /// <summary>The logical library name; <see cref=\"NativeLibraryName\"/> maps it per platform.</summary>",
             "    public const string LibraryName = \"gui_forms_abi\";", ""]
    for export in manifest["exports"]:
        parameters = ", ".join(f"{type_name(parameter['type'], known)} {identifier(parameter['name'])}"
                               for parameter in export["parameters"])
        lines.append("    [LibraryImport(LibraryName)]")
        lines.append("    [UnmanagedCallConv(CallConvs = new[] { typeof(CallConvCdecl) })]")
        lines.append(f"    public static partial {type_name(export['returns'], known)} {export['name']}({parameters});")
        lines.append("")
    for table, constant in table_ids(manifest):
        method = "get_" + table[len("gf_"):]
        lines.append(f"    /// <summary>Negotiates {table} at the manifest's version; a refusal leaves it zeroed.</summary>")
        lines.append(f"    public static gf_status {method}(out {table} table)")
        lines.append("    {")
        lines.append(f"        table = default;")
        lines.append(f"        fixed ({table}* storage = &table)")
        lines.append("        {")
        lines.append(f"            return gf_abi_get_table(Constants.{constant}, Constants.GF_ABI_MAJOR, "
                     f"Constants.GF_ABI_MINOR, storage, (ulong)sizeof({table}));")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
    lines += ["}", ""]
    return "\n".join(lines)


def render_layout(manifest: dict) -> str:
    lines = [HEADER, "using System.IO;", "", f"namespace {NAMESPACE};", "",
             "/// <summary>The manifest's sizes and offsets against the runtime's own layout.</summary>",
             "public static unsafe class Layout", "{",
             "    /// <summary>Writes one line per disagreement; returns how many there were.</summary>",
             "    public static int check(TextWriter output)", "    {", "        int failures = 0;"]
    for struct in manifest["structs"]:
        name = struct["name"]
        lines.append("        {")
        lines.append(f"            {name} value = default;")
        lines.append(f"            byte* start = (byte*)&value;")
        lines.append(f"            failures += expect(output, \"{name} size\", sizeof({name}), {struct['size']});")
        for field in struct["fields"]:
            member = identifier(field["name"])
            if array_shape(field["type"]) is not None:
                address = f"(byte*)value.{member}"
            else:
                address = f"(byte*)&value.{member}"
            lines.append(f"            failures += expect(output, \"{name}.{field['name']} offset\", "
                         f"(long)({address} - start), {field['offset']});")
        lines.append("        }")
    lines += ["        return failures;", "    }", "",
              "    private static int expect(TextWriter output, string what, long actual, long expected)", "    {",
              "        if (actual == expected)", "        {", "            return 0;", "        }",
              "        output.WriteLine($\"layout: {what} is {actual}, the manifest says {expected}\");",
              "        return 1;", "    }", "}", ""]
    return "\n".join(lines)



CPP_PREAMBLE = """// Generated from manifests/abi/gf_abi.json by `python3 tools/abi_bindings.py cpp`. Do not edit.
//
// Header-only C++ wrappers of the GUI.Forms C ABI (gf_abi.h). Each table is a
// class made by negotiation; each method calls exactly one slot, with the
// slot's own signature, and answers GF_STATUS_UNSUPPORTED_VERSION for a slot
// the library did not serve. The wrappers add no second contract: statuses,
// ownership and threading are gf_abi.h's.
#pragma once

#include "gui_forms/c/gf_abi.h"

namespace gui_forms::abi {
"""


def pascal(stem: str) -> str:
    return "".join(part.capitalize() for part in stem.split("_"))


def table_struct(manifest: dict, name: str) -> dict:
    for struct in manifest["structs"]:
        if struct["name"] == name:
            return struct
    raise BindingError(f"no struct {name}")


def cpp_class_name(table: str) -> str:
    return pascal(table[len("gf_"):-len("_table")]) + "Table"


CPP_COLUMNS = 120


def wrap_list(prefix: str, items: str, suffix: str) -> list[str]:
    """prefix + items + suffix on one line, or the items broken after commas
    and aligned under the first, so no line passes CPP_COLUMNS."""
    single = prefix + items + suffix
    if len(single) <= CPP_COLUMNS:
        return [single]
    indent = " " * len(prefix)
    parts = items.split(", ")
    lines = []
    current = prefix
    for index, part in enumerate(parts):
        piece = part + (", " if index + 1 < len(parts) else suffix)
        if current.strip() and len(current + piece.rstrip()) > CPP_COLUMNS and current != prefix:
            lines.append(current.rstrip())
            current = indent
        current += piece
    lines.append(current)
    return lines


def adopt_signature(class_name: str, name: str) -> list[str]:
    single = f"    [[nodiscard]] static {class_name} adopt(const {name}& adopted_table) noexcept {{"
    if len(single) <= CPP_COLUMNS:
        return [single]
    return [f"    [[nodiscard]] static {class_name} adopt(",
            f"        const {name}& adopted_table) noexcept {{"]


def cpp_table_class(struct: dict, constant: str) -> list[str]:
    name = struct["name"]
    class_name = cpp_class_name(name)
    lines = [f"// {name}, negotiated as {constant}.",
             f"class {class_name} {{",
             "public:",
             f"    {class_name}() noexcept : table_{{}} {{}}",
             "",
             "    // Negotiates the table at the header's version into output; a refusal",
             "    // leaves output serving nothing.",
             f"    [[nodiscard]] static gf_status negotiate({class_name}& output) noexcept {{",
             f"        {name} negotiated_table{{}};",
             f"        const gf_status negotiated = gf_abi_get_table({constant}, GF_ABI_MAJOR, GF_ABI_MINOR,",
             "                                                      &negotiated_table, sizeof(negotiated_table));",
             "        if (negotiated != GF_STATUS_OK) {",
             f"            output = {class_name}{{}};",
             "            return negotiated;",
             "        }",
             "        output.table_ = negotiated_table;",
             "        return GF_STATUS_OK;",
             "    }",
             "",
             "    // A table the caller negotiated through gf_abi_get_table.",
             *adopt_signature(class_name, name),
             f"        {class_name} adopted;",
             "        adopted.table_ = adopted_table;",
             "        return adopted;",
             "    }",
             "",
             f"    [[nodiscard]] const {name}& c_table() const noexcept {{ return table_; }}",
             ""]
    for field in struct["fields"][2:]:
        signature = field["signature"]
        parameters = ", ".join(f"{parameter['type']} {parameter['name']}" for parameter in signature["parameters"])
        arguments = ", ".join(parameter["name"] for parameter in signature["parameters"])
        end = field["offset"] + field["size"]
        lines += wrap_list(f"    [[nodiscard]] gf_status {field['name']}(", parameters,
                           ") const noexcept {")
        lines.append(f"        if (table_.struct_size < {end}u || table_.{field['name']} == nullptr) {{")
        lines.append("            return GF_STATUS_UNSUPPORTED_VERSION;")
        lines.append("        }")
        lines += wrap_list(f"        const gf_status called = table_.{field['name']}(", arguments, ");")
        lines.append("        return called;")
        lines.append("    }")
        lines.append("")
    lines += ["private:", f"    {name} table_;", "};", ""]
    return lines


def render_cpp(manifest: dict) -> str:
    lines = [CPP_PREAMBLE]
    for struct_name, constant in table_ids(manifest):
        lines += cpp_table_class(table_struct(manifest, struct_name), constant)
    lines.append(CPP_OWNERS.read_text(encoding="utf-8"))
    lines += ["} // namespace gui_forms::abi", ""]
    return "\n".join(lines)


def check_slot_map(header: str, manifest: dict) -> list[str]:
    """The 1:1 slot map, read from the header text rather than trusted from
    the generator: within each table's class every method body calls exactly
    its own slot (table_.<slot>(...)), and every slot has exactly one method."""
    problems = []
    for struct_name, _ in table_ids(manifest):
        struct = table_struct(manifest, struct_name)
        class_name = cpp_class_name(struct_name)
        start = header.find(f"class {class_name} {{")
        end = header.find("\n};", start)
        if start < 0 or end < 0:
            problems.append(f"{class_name} is missing")
            continue
        body = header[start:end]
        slots = [field["name"] for field in struct["fields"][2:]]
        methods = {slot: 0 for slot in slots}
        for chunk in body.split("    [[nodiscard]] gf_status ")[1:]:
            method = chunk.split("(", 1)[0]
            method_body = chunk.split("\n    }", 1)[0]
            called = [slot for slot in slots if f"table_.{slot}(" in method_body]
            if method not in methods:
                if called:
                    problems.append(f"{class_name}::{method} calls {called} but is no slot's method")
                continue
            if called != [method]:
                problems.append(f"{class_name}::{method} calls {called}, not exactly its own slot")
            methods[method] += 1
        for slot, count in methods.items():
            if count != 1:
                problems.append(f"{class_name}: slot {slot} has {count} methods")
    return problems


def cpp_write_or_check(manifest: dict, output: pathlib.Path, check: bool) -> int:
    text = render_cpp(manifest)
    current = output.read_text(encoding="utf-8") if output.exists() else None
    if not check and current != text:
        output.write_text(text, encoding="utf-8", newline="\n")
        current = text
    failed = 0
    if current != text:
        print(f"abi_bindings: {output.name} is stale; run `python3 tools/abi_bindings.py cpp`", file=sys.stderr)
        failed = 1
    for problem in check_slot_map(current or "", manifest):
        print(f"abi_bindings: slot map: {problem}", file=sys.stderr)
        failed = 1
    return failed

def csharp_files(manifest: dict) -> dict[str, str]:
    return {
        "Aliases.g.cs": render_aliases(manifest),
        "Types.g.cs": render_types(manifest),
        "Constants.g.cs": render_constants(manifest),
        "Exports.g.cs": render_exports(manifest),
        "Layout.g.cs": render_layout(manifest),
    }


def write_or_check(files: dict[str, str], output: pathlib.Path, check: bool) -> int:
    stale = []
    for name, text in files.items():
        path = output / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(name)
            continue
        output.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    present = {path.name for path in output.glob("*.g.cs")} if output.exists() else set()
    extra = sorted(present - set(files))
    if check:
        for name in stale:
            print(f"abi_bindings: {output.relative_to(ROOT).as_posix()}/{name} is stale; "
                  "run `python3 tools/abi_bindings.py csharp`", file=sys.stderr)
        for name in extra:
            print(f"abi_bindings: {name} is not generated from the manifest", file=sys.stderr)
        return 1 if stale or extra else 0
    for name in extra:
        (output / name).unlink()
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("language", choices=["csharp", "cpp"])
    parser.add_argument("--manifest", type=pathlib.Path, default=MANIFEST)
    parser.add_argument("--output", type=pathlib.Path, help="the output directory (csharp) or header (cpp)")
    parser.add_argument("--check", action="store_true", help="fail when a checked-in file is stale")
    arguments = parser.parse_args()
    manifest = json.loads(arguments.manifest.read_text(encoding="utf-8"))
    try:
        if arguments.language == "cpp":
            return cpp_write_or_check(manifest, (arguments.output or CPP_OUTPUT).resolve(), arguments.check)
        files = csharp_files(manifest)
    except BindingError as error:
        print(f"abi_bindings: {error}", file=sys.stderr)
        return 1
    return write_or_check(files, (arguments.output or CSHARP_OUTPUT).resolve(), arguments.check)


if __name__ == "__main__":
    sys.exit(main())
