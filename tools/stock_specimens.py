"""Write or check the stock specimen catalogue's generated table.

The stock specimen catalogue (``gui_forms/controls/specimen/stock_specimens``,
owner request 2026-11-11) holds one representative instance maker for every
control type of the control schema (``manifests/control-schema.json``, kind
``control``), in schema order, so that a theme palette is complete by
construction. This tool projects the schema and the registry
(``manifests/controls.json``: each type's header and category) into two C++
fragments the catalogue compiles:

- ``stock_specimen_includes.inc``: each type's header;
- ``stock_specimen_table.inc``: one ``StockSpecimen`` row per type: the
  control id, the registry category (the palette's family), the logical
  size it is laid out at, the sample text and the maker.

A type gets the generic maker (``make_plain<Type>``, or ``make_text<Type>``
when it has a writable ``text`` property) unless ``MAKERS`` below names one
written in ``stock_specimens.cpp`` (sample items, or what the type borrows).
A newly registered control therefore has a row as soon as this tool runs;
``--check`` fails while the committed fragments are stale.

Standard library only; Python 3.12+.
"""

