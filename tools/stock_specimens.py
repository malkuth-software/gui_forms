def sample_text(control_id: str) -> str:
    """The id as words, first letter capital: ``check_box`` is ``Check box``."""
    words: str = control_id.replace("_", " ")
    result: str = words[:1].upper() + words[1:]
    return result


def has_writable_text(entry: Mapping[str, object]) -> bool:
    """Whether the schema type has a writable ``text`` property."""
    properties: object = entry.get("properties", [])
    if not isinstance(properties, list):
        return False
    for item in properties:
        if isinstance(item, Mapping) and item.get("name") == "text" and item.get("writable") is True:
            return True
    return False


def number(value: float) -> str:
    """A C++ double literal."""
    text: str = repr(float(value))
    return text


def render(schema: Mapping[str, object], registry: Mapping[str, object]) -> tuple[str, str]:
    """The includes fragment and the table fragment."""
    types: object = schema["types"]
    controls_entries: object = registry["controls"]
    if not isinstance(types, list) or not isinstance(controls_entries, list):
        raise ValueError("the schema and the registry hold lists")
    by_id: dict[str, Mapping[str, object]] = {}
    for item in controls_entries:
        by_id[str(item["id"])] = item
    headers: list[str] = []
    rows: list[str] = []
    for entry in types:
        if entry["kind"] != "control":
            continue
        control_id: str = str(entry["id"])
        type_name: str = str(entry["type"])
        record: Mapping[str, object] | None = by_id.get(control_id)
        if record is None:
            raise ValueError(f"{control_id} is in the schema but not in the registry")
        header: str = str(record["header"])
        if header not in headers:
            headers.append(header)
        category: str = str(record["category"])
        size: tuple[float, float] = SIZES.get(control_id, CATEGORY_SIZES.get(category, DEFAULT_SIZE))
        maker: str = MAKERS.get(control_id, "")
        if not maker:
            maker = f"make_text<{type_name}>" if has_writable_text(entry) else f"make_plain<{type_name}>"
        rows.append(
            f'    {{"{control_id}", "{category}", Size{{{number(size[0])}, {number(size[1])}}}, '
            f'"{sample_text(control_id)}", &{maker}}},'
        )
    includes: str = HEADER + "".join(f'#include "{header}"\n' for header in headers)
    table: str = HEADER + "\n".join(rows) + "\n"
    return includes, table


def main(argv: Sequence[str] | None = None) -> int:
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed fragments are stale")
    arguments: argparse.Namespace = parser.parse_args(argv)
    schema: Mapping[str, object] = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    registry: Mapping[str, object] = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    includes, table = render(schema, registry)
    outputs: list[tuple[Path, str]] = [(INCLUDES_PATH, includes), (TABLE_PATH, table)]
    if arguments.check:
        stale: list[str] = []
        for path, text in outputs:
            current: str = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            print("stock specimens: stale " + ", ".join(stale) + "; run python3 -B tools/stock_specimens.py",
                  file=sys.stderr)
            return 1
        print("stock specimens: current")
        return 0
    OUTPUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    for path, text in outputs:
        path.write_text(text, encoding="utf-8")
    print(f"stock specimens: wrote {INCLUDES_PATH.relative_to(ROOT)} and {TABLE_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
