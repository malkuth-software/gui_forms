"""generate_hostile_macros writes the hostile-macro conformance header.

The consumer surface must compile whatever macros the consumer defined
before including it. This header defines every identifier the surface uses
and the consumer is entitled to define (tools/consumer_macros.py says which)
as a macro that fails loudly when expanded:

    #define near _Pragma("GCC error \\"hostile consumer macro expanded: near\\"") ...

It is not a list of known macros: the set is every open identifier of the
headers reached, so a macro windows.h adds tomorrow, or one in the client's
own code, is covered by construction. A test translation unit includes the
generated header and then the consumer headers, and must compile.

The translation unit names the generated header in its first first-party
include; the includes after it are the seeds (the shield's two headers are
not scanned). A unit of the module path imports gui_forms after the header
instead: its seeds are then the module's umbrellas, given with --seed. The standard headers the
closure includes are included first, before any definition, since the
consumer may not define standard names ([macro.names]).

    python3 -B tools/generate_hostile_macros.py \\
        --translation-unit tests/hostile_macros/hostile_macro_minimal.cpp \\
        --include-root include --include-root STXLIB/include \\
        --standard-names tests/hostile_macros/standard_library_names.txt \\
        --output build/hostile_macros/hostile_macros_minimal.h \\
        --report build/hostile_macros/hostile_macros_minimal.txt

--surface include/gui_forms classifies first-party macros and configuration
names over the whole surface, as the shield does. --include-directories-file reads further roots, one per line (CMake writes
the consumer's include directories there). The report lists every hostile
identifier with the header and line of its first use: the failures the test
would show while the surface is unguarded.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import consumer_macros

PRAGMA_BODY: str = '_Pragma("GCC error \\"hostile consumer macro expanded: {name}\\"")'


def seeds_of(translation_unit: Path, generated_name: str) -> list[consumer_macros.Include]:
    """The includes after the one that names the generated header."""
    scan: consumer_macros.HeaderScan = consumer_macros.scan_header(consumer_macros.read_source(translation_unit))
    seeds: list[consumer_macros.Include] = []
    found: bool = False
    for include in scan.includes:
        if found:
            seeds.append(include)
        elif Path(include.spelling).name == generated_name:
            found = True
    if not found:
        raise SystemExit(f'{translation_unit}: no include of {generated_name}')
    return seeds


def read_roots(arguments: argparse.Namespace) -> list[Path]:
    roots: list[Path] = [Path(root).resolve() for root in arguments.include_root]
    if arguments.include_directories_file:
        text: str = arguments.include_directories_file.read_text(encoding='utf-8')
        for line in text.splitlines():
            directory: str = line.strip()
            if directory and Path(directory).is_dir() and Path(directory).resolve() not in roots:
                roots.append(Path(directory).resolve())
    return roots


def display_path(path: Path, roots: list[Path]) -> str:
    for root in roots:
        if path.is_relative_to(root):
            return str(path.relative_to(root))
    return str(path)


def render_header(translation_unit: Path, closure: consumer_macros.Closure,
                  classification: consumer_macros.Classification) -> str:
    names: list[str] = sorted(classification.hostile)
    lines: list[str] = [
        f'/* Generated by tools/generate_hostile_macros.py from {translation_unit.name}; do not edit.',
        f'   {len(closure.headers)} first-party headers reached, {len(names)} identifiers defined.',
        '   Each definition fails the compile, naming itself, wherever it is expanded. */',
        '',
        '/* The standard headers the consumer surface includes come first: a',
        '   consumer may not define standard names before them ([macro.names]). */',
    ]
    for spelling in closure.system_includes:
        lines.append(f'#if __has_include(<{spelling}>)')
        lines.append(f'#include <{spelling}>')
        lines.append('#endif')
    lines.append('')
    for name in names:
        lines.append(f'#define {name} {PRAGMA_BODY.format(name=name)} hostile_consumer_macro_{name}')
    return '\n'.join(lines) + '\n'


def render_report(closure: consumer_macros.Closure, classification: consumer_macros.Classification,
                  roots: list[Path]) -> str:
    lines: list[str] = [
        f'headers reached: {len(closure.headers)}',
        f'hostile identifiers: {len(classification.hostile)}',
    ]
    for reason in sorted(classification.excluded):
        lines.append(f'excluded ({reason}): {len(classification.excluded[reason])}')
    lines.append('')
    lines.append('# First-party #define of a name open to the consumer (the surface overrides the consumer)')
    for name in sorted(classification.unprefixed_macros):
        lines.append(f'{name}\t{display_path(classification.unprefixed_macros[name], roots)}')
    lines.append('# First-party #undef of a name open to the consumer')
    for name in sorted(classification.undefined_macros):
        lines.append(f'{name}\t{display_path(classification.undefined_macros[name], roots)}')
    lines.append('# Configuration names read in #if lines (excluded from the test)')
    for name in sorted(classification.excluded.get('configuration', ())):
        lines.append(name)
    lines.append('# Hostile identifiers: first use, header and line')
    by_use: list[tuple[str, int, str]] = []
    for name, (path, line) in classification.hostile.items():
        by_use.append((display_path(path, roots), line, name))
    by_use.sort()
    for header, line, name in by_use:
        lines.append(f'{header}:{line}\t{name}')
    return '\n'.join(lines) + '\n'


def main(argument_list: list[str]) -> int:
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--translation-unit', type=Path, required=True)
    parser.add_argument('--include-root', action='append', default=[])
    parser.add_argument('--seed', action='append', default=[], help='a further seed header, as included')
    parser.add_argument('--include-directories-file', type=Path)
    parser.add_argument('--standard-names', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path)
    parser.add_argument('--surface', type=Path,
                        help='the surface directory (include/gui_forms) whose macros and #if names are excluded')
    arguments: argparse.Namespace = parser.parse_args(argument_list)

    roots: list[Path] = read_roots(arguments)
    seeds: list[consumer_macros.Include] = seeds_of(arguments.translation_unit, arguments.output.name)
    for spelling in arguments.seed:
        seeds.append(consumer_macros.Include(spelling, False, 1))
    if not seeds:
        raise SystemExit(f'{arguments.translation_unit}: no consumer header after {arguments.output.name}, '
                         'and no --seed')
    closure: consumer_macros.Closure = consumer_macros.compute_closure(
        seeds, roots, arguments.translation_unit.resolve().parent)
    if not closure.headers:
        raise SystemExit(f'{arguments.translation_unit}: no seed resolves under {roots}')
    standard_names: frozenset[str] = consumer_macros.load_standard_names(arguments.standard_names)
    defined: set[str] = set()
    conditions: set[str] = set()
    if arguments.surface:
        # The whole surface decides what is a first-party macro or a
        # configuration name, exactly as the shield (tools/consumer_shield.py) does.
        surface_root: Path = arguments.surface.resolve().parent
        surface: consumer_macros.Closure = consumer_macros.compute_closure(
            consumer_macros.surface_seeds(arguments.surface.resolve(), surface_root), roots, surface_root)
        defined, conditions = consumer_macros.surface_exclusions(surface)
    classification: consumer_macros.Classification = consumer_macros.classify(
        closure.headers, standard_names, first_party_macros=defined, configuration=conditions)

    header_text: str = render_header(arguments.translation_unit, closure, classification)
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    # Rewritten only on change, so a build does not recompile the test for nothing.
    if not arguments.output.is_file() or arguments.output.read_text(encoding='utf-8') != header_text:
        arguments.output.write_text(header_text, encoding='utf-8')
    if arguments.report:
        arguments.report.write_text(render_report(closure, classification, roots), encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
