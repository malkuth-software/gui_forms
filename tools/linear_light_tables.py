#!/usr/bin/env python3
"""Writes the sRGB tables of linear-light gradient interpolation.

Gradients interpolate in linear light (owner, 2026-11-16): each stop is
decoded from sRGB to linear light, the stops are interpolated there, and the
result is encoded back to an sRGB byte. The engine does both conversions by
table, in integers, so no host libm is called and every host gives the same
bytes (gui_forms/types/linear_light/linear_light.hpp). This script writes the
two tables to include/gui_forms/types/linear_light/detail/linear_light_tables.hpp:

- linear_light_decode_table[v], v an sRGB byte: the sRGB curve's linear
  light, round(65535 * decode(v / 255)), in 16-bit fixed point;
- linear_light_encode_thresholds[v], v in 0..254: the least 16-bit linear
  value that encodes to v + 1 or more, ceil(65535 * decode((v + 0.5) / 255)).
  A linear value encodes to the number of thresholds at or below it, which
  is the byte whose encoded value is nearest, rounded half up.

decode is the sRGB curve (IEC 61966-2-1): s / 12.92 for s <= 0.04045, else
((s + 0.055) / 1.055) ^ 2.4. The power is evaluated exactly, in rationals:
2.4 = 12 / 5, so y = 65535 * x ^ (12 / 5) is compared through
y ^ 5 = 65535 ^ 5 * x ^ 12. The tables are therefore the same on every host
and every Python. The script checks that every byte survives a round trip.

Usage:

    python3 -B tools/linear_light_tables.py           # write the tables
    python3 -B tools/linear_light_tables.py --check   # fail when they are stale
"""

from __future__ import annotations

import argparse
import sys
from fractions import Fraction
from pathlib import Path

ROOT: Path = Path(__file__).resolve().parent.parent
OUTPUT: Path = ROOT / 'include/gui_forms/types/linear_light/detail/linear_light_tables.hpp'
SCALE: int = 65535
LINEAR_LIMIT: Fraction = Fraction(4045, 100000)


def scaled_fifth_power(encoded: Fraction) -> Fraction:
    """65535 ^ 5 * ((s + 0.055) / 1.055) ^ 12, the fifth power of the scaled
    linear value of an sRGB value above the curve's linear segment."""
    base: Fraction = (encoded + Fraction(55, 1000)) / Fraction(1055, 1000)
    power: Fraction = Fraction(SCALE) ** 5 * base ** 12
    return power


def least_root_at_or_above(power: Fraction) -> int:
    """The least integer y with y ^ 5 >= power (power >= 0)."""
    low: int = 0
    high: int = SCALE
    while low < high:
        middle: int = (low + high) // 2
        if Fraction(middle) ** 5 >= power:
            high = middle
        else:
            low = middle + 1
    return low


def rounded_scaled(encoded: Fraction) -> int:
    """round(65535 * decode(encoded)), halves up."""
    if encoded <= LINEAR_LIMIT:
        exact: Fraction = Fraction(SCALE) * encoded / Fraction(1292, 100)
        return int(exact + Fraction(1, 2))
    power: Fraction = scaled_fifth_power(encoded)
    # round(y) = the least integer n with n + 0.5 > y, that is (n + 0.5) ^ 5 > power.
    low: int = 0
    high: int = SCALE
    while low < high:
        middle: int = (low + high) // 2
        if (Fraction(middle) + Fraction(1, 2)) ** 5 > power:
            high = middle
        else:
            low = middle + 1
    return low


def ceiling_scaled(encoded: Fraction) -> int:
    """ceil(65535 * decode(encoded))."""
    if encoded <= LINEAR_LIMIT:
        exact: Fraction = Fraction(SCALE) * encoded / Fraction(1292, 100)
        whole: int = exact.numerator // exact.denominator
        return whole if Fraction(whole) == exact else whole + 1
    return least_root_at_or_above(scaled_fifth_power(encoded))


def tables() -> tuple[list[int], list[int]]:
    decode: list[int] = [rounded_scaled(Fraction(value, 255)) for value in range(256)]
    thresholds: list[int] = [ceiling_scaled(Fraction(2 * value + 1, 510)) for value in range(255)]
    for value in range(256):
        encoded: int = sum(1 for threshold in thresholds if threshold <= decode[value])
        if encoded != value:
            raise SystemExit(f'sRGB byte {value} does not survive the round trip (encodes to {encoded})')
    for index in range(1, 255):
        if thresholds[index] <= thresholds[index - 1]:
            raise SystemExit(f'thresholds {index - 1} and {index} are not increasing')
    return decode, thresholds


def rows(values: list[int], per_row: int) -> str:
    lines: list[str] = []
    for start in range(0, len(values), per_row):
        chunk: list[int] = values[start:start + per_row]
        lines.append('    ' + ', '.join(f'{value}U' for value in chunk) + ',')
    return '\n'.join(lines)


def render() -> str:
    decode, thresholds = tables()
    text: str = (
        '// Generated by tools/linear_light_tables.py; do not edit.\n'
        '// The sRGB curve in 16-bit fixed point, evaluated exactly in rationals.\n'
        '#pragma once\n'
        '\n'
        '#include <array>\n'
        '#include <cstdint>\n'
        '\n'
        'namespace gui_forms::detail {\n'
        '\n'
        '// sRGB byte to linear light: round(65535 * decode(v / 255)).\n'
        'inline constexpr std::array<std::uint16_t, 256> linear_light_decode_table{{\n'
        + rows(decode, 12) + '\n'
        '}};\n'
        '\n'
        '// Entry v: the least linear value that encodes to v + 1 or more,\n'
        '// ceil(65535 * decode((v + 0.5) / 255)); increasing.\n'
        'inline constexpr std::array<std::uint16_t, 255> linear_light_encode_thresholds{{\n'
        + rows(thresholds, 12) + '\n'
        '}};\n'
        '\n'
        '} // namespace gui_forms::detail\n')
    return text


def main() -> int:
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail when the checked-in tables are stale')
    args: argparse.Namespace = parser.parse_args()
    text: str = render()
    if args.check:
        current: str = OUTPUT.read_text(encoding='utf-8') if OUTPUT.is_file() else ''
        if current != text:
            print(f'{OUTPUT.relative_to(ROOT)} is stale: run python3 -B tools/linear_light_tables.py',
                  file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
