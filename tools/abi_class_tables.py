#!/usr/bin/env python3
"""Generates the C ABI's class tables: GUI.Forms' On* hooks for C and C#.

The owner chose generated class tables (projects:desks/coordinator/ON_HOOKS_PLAN.md,
2026-11-12; the sealed-interface record is decisions/ABI_CLASS_TABLES_DECISION.md
there). A C++ raiser is a protected virtual whose base raises the event (P-8). A
*segment* is one class's own raisers as a C record of entries; a *class table* is
a header plus one pointer per segment of the class's chain; the *bridge* is the
C++ class over a stock class that calls the table where the raiser runs.

Inputs:

- ``manifests/members.json``: a hook row with a ``raiser`` field
  (``{"cpp": "Class::on_x_changed", "interaction": "x_changed" or null}``) is an
  entry; a row without one is not yet;
- the public headers (``tools/api_docs_parse.py``): the class hierarchy, and the
  raiser's declaration, which must be a protected ``virtual void on_x()``;
- ``src/``: the raiser's body, which says which interaction its base emits
  (``publish_change(x_changed_, ...)``);
- ``manifests/control-schema.json``: the types, their properties and interactions;
- the event catalogue (``tools/abi_event_catalog.py``'s declarations): the
  interaction is declared by the raiser's class or a base;
- ``manifests/abi/gf_abi.json``: the ABI types the outputs name exist.

Outputs (``--check`` regenerates them in memory and fails on any difference):

- ``include/gui_forms/c/gf_abi_classes.h``: ids, segments, class tables and the
  ``gf_classes_table`` (``gf_abi.h`` includes it);
- ``src/abi/stable/classes/generated/abi_class_segments.hpp`` and
  ``abi_class_registry.cpp``: one bridge layer per segment, the creation registry
  ``classes.create`` dispatches through, and the base functions;
- ``bindings/csharp/GuiForms.Forms/Generated/*.g.cs``: the ``OnX`` virtuals, their
  ``[UnmanagedCallersOnly]`` entries, the segment fillers and table builders;
- ``manifests/abi/class_tables.json``: the append-only ledger of class ids,
  segment entries and class tables. The generator only appends to it: a raiser
  that disappears, or a ledger edited to lose or reorder an entry or id, fails;
- ``tests/abi/conformance/gf_conformance_classes.c`` (the conformance kit's part
  for the plan's guarantees) and
  ``tests/abi/csharp/GuiForms.Forms.Tests/ClassHookTests.g.cs``.

A class table exists for every creatable control class that is not ``final``
(a bridge derives from the stock class). A segment exists for every class that
declares an entry; a segment no derivable class reaches waits for its class to
become derivable.
"""

