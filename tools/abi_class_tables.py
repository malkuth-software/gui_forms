def outputs(model: Model) -> dict[Path, str]:
    files: dict[Path, str] = {
        HEADER: render_header(model),
        CPP_DIR / "abi_class_segments.hpp": render_segments(model),
        CPP_DIR / "abi_class_registry.cpp": render_registry(model),
        LEDGER: json.dumps(model.ledger, indent=2) + "\n",
        C_TEST: render_c_test(model),
        CSHARP_TEST: render_csharp_test(model),
    }
    name: str = ""
    text: str = ""
    for name, text in csharp_files(model).items():
        files[CSHARP_DIR / name] = text
    return files


def stale_extras(files: dict[Path, str]) -> list[Path]:
    """Generated C# files no longer produced."""
    present: list[Path] = sorted(CSHARP_DIR.glob("*.g.cs")) if CSHARP_DIR.exists() else []
    return [path for path in present if path not in files]


def main(argv: list[str] | None = None) -> int:
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a committed output differs")
    parser.add_argument("--previous", type=Path,
                        help="an earlier ledger the current one must extend (append-only check)")
    arguments: argparse.Namespace = parser.parse_args(argv)
    try:
        model: Model = build_model()
    except TableError as error:
        print(f"abi_class_tables: {error}", file=sys.stderr)
        return 1
    failed: int = 0
    if arguments.previous is not None:
        problem: str = ""
        for problem in check_append_only(load_json(arguments.previous), model.ledger):
            print(f"abi_class_tables: append-only: {problem}", file=sys.stderr)
            failed = 1
    files: dict[Path, str] = outputs(model)
    path: Path
    text: str = ""
    for path, text in files.items():
        current: str | None = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if arguments.check:
            print(f"abi_class_tables: {path.relative_to(ROOT).as_posix()} is stale; "
                  "run `python3 -B tools/abi_class_tables.py`", file=sys.stderr)
            failed = 1
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    for path in stale_extras(files):
        if arguments.check:
            print(f"abi_class_tables: {path.relative_to(ROOT).as_posix()} is not generated", file=sys.stderr)
            failed = 1
            continue
        path.unlink()
    if not failed:
        entries: int = sum(len(raisers) for raisers in model.raisers.values())
        print(f"abi_class_tables: {len(model.ledger['classes'])} class ids, {len(model.raisers)} segments "
              f"({entries} entries), {len(model.creatable)} class tables"
              f"{' (checked)' if arguments.check else ''}")
    return failed


if __name__ == "__main__":
    sys.exit(main())
