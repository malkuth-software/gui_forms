def render_segments(model: Model) -> str:
    lines: list[str] = [GENERATED_CPP,
                        "// One bridge layer per segment: Base is the stock class, or a layer over it.",
                        "// Included only by abi_class_registry.cpp.",
                        "", "#pragma once", "", '#include "../abi_class_bridge.hpp"', ""]
    headers: list[str] = sorted({model.classes[name].header[len("include/"):] for name in model.raisers})
    header: str = ""
    for header in headers:
        lines.append(f'#include "{header}"')
    lines += ["", "namespace gui_forms::abi1 {", "", "// The base functions an entry receives, one per raiser."]
    name: str = ""
    raisers: list[Raiser] = []
    raiser: Raiser
    for name, raisers in model.raisers.items():
        for raiser in raisers:
            lines.append(f"gf_status GF_CALL base_{model.classes[name].snake}_{raiser.method}(gf_object self, "
                         "gf_event* event) noexcept;")
    lines.append("")
    for name, raisers in model.raisers.items():
        snake: str = model.classes[name].snake
        layer: str = f"{name}HooksLayer"
        lines += [f"// {name}'s raisers ({constant(model, name)}).",
                  "template <typename Base>",
                  f"class {layer} : public Base {{",
                  "public:",
                  "    using Base::Base;",
                  "",
                  "protected:"]
        for raiser in raisers:
            index: int = entry_index(model, raiser)
            lines += [f"    void {raiser.method}() override {{",
                      f"        const HookKey hook{{{constant(model, name)}, {index}U}};",
                      "        const gf_hook_entry entry = (*this).hook_entry(hook);",
                      "        const bool entered = entry != nullptr &&",
                      f'                             (*this).enter_hook(*this, entry, hook, "{raiser.property}",',
                      f"                                                &base_{snake}_{raiser.method});",
                      "        if (!entered) {",
                      f"            Base::{raiser.method}();",
                      "        }",
                      "    }",
                      ""]
        lines += [f"    // Runs the raiser below this layer for one of {name}'s hooks; another",
                  "    // class's hook goes to the layers further in.",
                  "    [[nodiscard]] bool run_layer_base(HookKey hook) {",
                  f"        if (hook.class_id != {constant(model, name)}) {{",
                  "            const bool inner = Base::run_layer_base(hook);",
                  "            return inner;",
                  "        }",
                  "        bool ran = true;",
                  "        switch (hook.entry) {"]
        for raiser in raisers:
            lines += [f"        case {entry_index(model, raiser)}U:",
                      f"            Base::{raiser.method}();",
                      "            break;"]
        lines += ["        default:",
                  "            ran = false;",
                  "            break;",
                  "        }",
                  "        return ran;",
                  "    }",
                  "};",
                  ""]
    lines += ["} // namespace gui_forms::abi1", ""]
    return "\n".join(lines)


def layers_of(model: Model, name: str) -> str:
    """The layer composition of name's bridge: base segments innermost."""
    text: str = f"BridgeState<{name}>"
    segment: str = ""
    for segment in table_segments(model, name):
        text = f"{segment}HooksLayer<{text}>"
    return text


