def cs_class(model: Model, name: str) -> str:
    info: ClassInfo = model.classes[name]
    parent: str = info.chain[1] if len(info.chain) > 1 else ""
    base: str = f" : {parent}" if parent else ""
    lines: list[str] = [GENERATED_CS, "using System;", "using System.Runtime.CompilerServices;",
                        "using System.Runtime.InteropServices;", "using GuiForms.Interop;", "",
                        "namespace GuiForms.Forms;", ""]
    lines.append(f"public partial class {name}{base}")
    lines.append("{")
    if name in model.creatable:
        lines += [f"    /// <summary>Makes the native {name} through its class table (classes.create), with",
                  "    /// stable_id as objects.create takes it. A derived managed class shares the native",
                  "    /// class and overrides its hooks.</summary>",
                  f"    public {name}(string stable_id)",
                  "        : base(ClassCreation.deferred)",
                  "    {",
                  f"        create_native(Constants.{constant(model, name)}, stable_id);",
                  "    }",
                  ""]
    lines += ["    /// <summary>For a derived class's constructor, which makes the native object.</summary>",
              f"    protected {name}(ClassCreation creation)",
              "        : base(creation)",
              "    {",
              "    }"]
    raisers: list[Raiser] = model.raisers.get(name, []) if name in reachable_segments(model) else []
    raiser: Raiser
    for raiser in raisers:
        key: str = f"HookKeys.{model.classes[name].snake}_{raiser.method}"
        lines += ["",
                  f"    /// <summary>{raiser.cpp_class}::{raiser.method}: {raiser_text(raiser)}. Windows Forms'",
                  f"    /// {', '.join(sorted(set(raiser.winforms)))}. Call the base to run the subscribers.</summary>",
                  f"    [Hook(Constants.{constant(model, name)}, {entry_index(model, raiser)}u)]",
                  f"    protected virtual void {raiser.hook_name}(EventArgs e)",
                  "    {",
                  f'        Hooks.call_base(this, {key}, "{raiser.property}"u8);',
                  "    }",
                  "",
                  "    [UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]",
                  f"    private static unsafe void {raiser.hook_name}Entry(void* instance, gf_object self, gf_event* "
                  "native,",
                  "        delegate* unmanaged[Cdecl]<gf_object, gf_event*, gf_status> base_raiser)",
                  "    {",
                  "        // No exception crosses into the library: it is recorded with the frames",
                  "        // it was thrown under (CallbackFailure, the exception reflection path).",
                  "        try",
                  "        {",
                  f"            {name} target = ({name})Instances.from(instance);",
                  f"            using HookFrame frame = HookFrame.enter(target, {key}, self, native, base_raiser);",
                  f"            target.{raiser.hook_name}(EventArgs.Empty);",
                  "        }",
                  "        catch (Exception failure)",
                  "        {",
                  "            CallbackFailure.record(failure);",
                  "        }",
                  "    }"]
    if raisers:
        snake: str = model.classes[name].snake
        lines += ["",
                  f"    /// <summary>Fills {segment_type(model, name)}: an entry for each hook in overridden.</summary>",
                  f"    internal static unsafe void fill_{snake}_segment({segment_type(model, name)}* segment, "
                  "HookSet overridden)",
                  "    {",
                  f"        (*segment).struct_size = (uint)sizeof({segment_type(model, name)});",
                  f"        (*segment).class_id = Constants.{constant(model, name)};"]
        for raiser in raisers:
            lines += [f"        if (overridden.contains(HookKeys.{snake}_{raiser.method}))",
                      "        {",
                      f"            (*segment).{raiser.method} = &{raiser.hook_name}Entry;",
                      "        }"]
        lines.append("    }")
    lines += ["}", ""]
    return "\n".join(lines)


def cs_keys(model: Model) -> str:
    lines: list[str] = [GENERATED_CS, "using GuiForms.Interop;", "", "namespace GuiForms.Forms;", "",
                        "/// <summary>Every hook of the class tables: its class and its entry.</summary>",
                        "public static class HookKeys", "{"]
    reached: set[str] = reachable_segments(model)
    name: str = ""
    raisers: list[Raiser] = []
    for name, raisers in model.raisers.items():
        if name not in reached:
            continue
        snake: str = model.classes[name].snake
        raiser: Raiser
        for raiser in raisers:
            lines.append(f"    public static readonly HookKey {snake}_{raiser.method} = "
                         f"new HookKey(Constants.{constant(model, name)}, {entry_index(model, raiser)}u);")
    lines += ["}", ""]
    return "\n".join(lines)


def cs_shapes(model: Model) -> str:
    lines: list[str] = [GENERATED_CS, "using System;", "using System.Runtime.InteropServices;",
                        "using GuiForms.Interop;", "", "namespace GuiForms.Forms;", "",
                        "/// <summary>Builds the native class table of each class: the header, the segment",
                        "/// pointers and the segments in one block of native memory, which the caller",
                        "/// keeps for the process (ClassTables).</summary>",
                        "internal static unsafe class ClassShapes", "{",
                        "    internal static gf_class_header* build(gf_class_id class_id, HookSet overridden)",
                        "    {",
                        "        switch (class_id)",
                        "        {"]
    name: str = ""
    for name in model.creatable:
        lines += [f"        case Constants.{constant(model, name)}:",
                  f"            return build_{model.classes[name].snake}(overridden);"]
    lines += ["        default:",
              "            throw new ArgumentOutOfRangeException(nameof(class_id), class_id, "
              "\"no class table has this class id\");",
              "        }",
              "    }"]
    for name in model.creatable:
        snake: str = model.classes[name].snake
        segments: list[str] = table_segments(model, name)
        size: str = " + ".join([f"sizeof({table_type(model, name)})"] +
                               [f"sizeof({segment_type(model, segment)})" for segment in segments])
        lines += ["",
                  f"    private static gf_class_header* build_{snake}(HookSet overridden)",
                  "    {",
                  f"        nuint size = (nuint)({size});",
                  "        byte* block = (byte*)NativeMemory.AllocZeroed(size);",
                  f"        {table_type(model, name)}* table = ({table_type(model, name)}*)block;",
                  f"        byte* next = block + sizeof({table_type(model, name)});"]
        segment: str = ""
        for segment in segments:
            field_name: str = model.classes[segment].snake
            lines += [f"        {segment_type(model, segment)}* {field_name} = ({segment_type(model, segment)}*)next;",
                      f"        next += sizeof({segment_type(model, segment)});",
                      f"        {segment}.fill_{field_name}_segment({field_name}, overridden);",
                      f"        (*table).{field_name} = {field_name};"]
        lines += ["        (*table).header.struct_size = (uint)sizeof(gf_class_header);",
                  "        (*table).header.abi_minor = Constants.GF_ABI_MINOR;",
                  f"        (*table).header.class_id = Constants.{constant(model, name)};",
                  f"        (*table).header.segment_count = {len(segments)}u;",
                  "        (*table).header.release = &ClassObjects.release_instance;",
                  "        return &(*table).header;",
                  "    }"]
    lines += ["}", ""]
    return "\n".join(lines)


def csharp_files(model: Model) -> dict[str, str]:
    files: dict[str, str] = {}
    wanted: list[str] = []
    name: str = ""
    for name in model.creatable:
        chain: str = ""
        for chain in reversed(model.classes[name].chain):
            if chain != "Component" and chain not in wanted:
                wanted.append(chain)
    for name in wanted:
        files[f"{name}.Hooks.g.cs"] = cs_class(model, name)
    files["HookKeys.g.cs"] = cs_keys(model)
    files["ClassShapes.g.cs"] = cs_shapes(model)
    return files


