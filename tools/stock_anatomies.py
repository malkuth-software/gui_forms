"""Write or check the stock controls' anatomy table compiled into the core.

The default theme's sheets (stage T4, phase 3) are compiled at first use, and
their selectors name stock control types, parts and states. The selector
vocabulary needs each stock control's anatomy, which the controls library
declares and the core cannot reach. This tool projects the anatomies of the
control schema (``manifests/control-schema.json``, written from a laid-out
Gallery) into ``src/core/theme/stock_anatomies/stock_anatomies.inc``, a C++
table the core compiles; ``--check`` proves the committed table is current.

Standard library only; Python 3.12+.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

ROOT: Path = Path(__file__).resolve().parent.parent
SCHEMA_PATH: Path = ROOT / "manifests" / "control-schema.json"
TABLE_PATH: Path = ROOT / "src" / "core" / "theme" / "stock_anatomies" / "stock_anatomies.inc"

HEADER: str = (
    "// Generated by tools/stock_anatomies.py from manifests/control-schema.json;\n"
    "// do not edit. Regenerate with `python3 -B tools/stock_anatomies.py`.\n"
)


def state_list(states: Sequence[str]) -> str:
    """A braced list of AnatomyState enumerators."""
    names: list[str] = ["AnatomyState::" + state for state in states]
    result: str = "{" + ", ".join(names) + "}"
    return result


def custom_list(states: Sequence[str]) -> str:
    """A braced list of custom state declarations."""
    names: list[str] = ['CustomStateDeclaration{.name = "' + state + '"}' for state in states]
    result: str = "{" + ", ".join(names) + "}"
    return result


def array_line(name: str, element: str, values: str, count: int) -> str:
    """One constexpr array definition, or an empty span's stand-in."""
    if count == 0:
        return ""
    result: str = "constexpr std::array<" + element + ", " + str(count) + "> " + name + "{" + values + "};\n"
    return result


def span_of(name: str, count: int) -> str:
    """The span initializer for an array written by array_line."""
    if count == 0:
        return "{}"
    return name


def part_lines(prefix: str, parts: Sequence[Mapping[str, object]]) -> tuple[str, str]:
    """The part arrays of one control or item system: (definitions, initializer)."""
    lines: list[str] = []
    entries: list[str] = []
    for index, part in enumerate(parts):
        states: Sequence[str] = part["states"]  # type: ignore[assignment]
        states_name: str = prefix + "_part_" + str(index) + "_states"
        lines.append(array_line(states_name, "AnatomyState", state_list(states)[1:-1], len(states)))
        composed: object = part["composed_from"]
        composed_text: str = "" if composed is None else str(composed)
        entries.append(
            "PartDeclaration{.name = \"" + str(part["name"]) + "\", .role = PartRole::" + str(part["role"]) +
            ", .composed_from = \"" + composed_text + "\", .states = " + span_of(states_name, len(states)) + "}"
        )
    parts_name: str = prefix + "_parts"
    lines.append(array_line(parts_name, "PartDeclaration", ", ".join(entries), len(entries)))
    return "".join(lines), span_of(parts_name, len(entries))


def control_lines(index: int, control: Mapping[str, object]) -> tuple[str, str]:
    """The arrays of one control and its ControlAnatomy initializer."""
    prefix: str = "stock_" + str(index)
    lines: list[str] = []
    parts: Sequence[Mapping[str, object]] = control["parts"]  # type: ignore[assignment]
    definitions, parts_span = part_lines(prefix, parts)
    lines.append(definitions)
    states: Sequence[str] = control["states"]  # type: ignore[assignment]
    states_name: str = prefix + "_states"
    lines.append(array_line(states_name, "AnatomyState", state_list(states)[1:-1], len(states)))
    custom: Sequence[str] = control["custom_states"]  # type: ignore[assignment]
    custom_name: str = prefix + "_custom"
    lines.append(array_line(custom_name, "CustomStateDeclaration", custom_list(custom)[1:-1], len(custom)))
    systems: Sequence[Mapping[str, object]] = control["item_systems"]  # type: ignore[assignment]
    system_entries: list[str] = []
    for system_index, system in enumerate(systems):
        system_prefix: str = prefix + "_item_" + str(system_index)
        system_parts: Sequence[Mapping[str, object]] = system["parts"]  # type: ignore[assignment]
        system_definitions, system_parts_span = part_lines(system_prefix, system_parts)
        lines.append(system_definitions)
        system_states: Sequence[str] = system["states"]  # type: ignore[assignment]
        system_states_name: str = system_prefix + "_states"
        lines.append(array_line(system_states_name, "AnatomyState", state_list(system_states)[1:-1],
                                len(system_states)))
        system_custom: Sequence[str] = system["custom_states"]  # type: ignore[assignment]
        system_custom_name: str = system_prefix + "_custom"
        lines.append(array_line(system_custom_name, "CustomStateDeclaration", custom_list(system_custom)[1:-1],
                                len(system_custom)))
        system_entries.append(
            "ItemSystemDeclaration{.name = \"" + str(system["name"]) + "\", .parts = " + system_parts_span +
            ", .states = " + span_of(system_states_name, len(system_states)) + ", .custom_states = " +
            span_of(system_custom_name, len(system_custom)) + "}"
        )
    systems_name: str = prefix + "_items"
    lines.append(array_line(systems_name, "ItemSystemDeclaration", ", ".join(system_entries), len(system_entries)))
    initializer: str = (
        "ControlAnatomy{.control_id = \"" + str(control["id"]) + "\", .parts = " + parts_span + ", .states = " +
        span_of(states_name, len(states)) + ", .custom_states = " + span_of(custom_name, len(custom)) +
        ", .item_systems = " + span_of(systems_name, len(system_entries)) + "}"
    )
    return "".join(lines), initializer


def render(schema: Mapping[str, object]) -> str:
    """The whole table for the controls (not components or services) of `schema`."""
    types: Sequence[Mapping[str, object]] = schema["types"]  # type: ignore[assignment]
    controls: list[Mapping[str, object]] = [entry for entry in types if entry["kind"] == "control"]
    lines: list[str] = [HEADER, "\n"]
    initializers: list[str] = []
    for index, control in enumerate(controls):
        definitions, initializer = control_lines(index, control)
        lines.append(definitions)
        initializers.append("    " + initializer)
    lines.append("constexpr std::array<ControlAnatomy, " + str(len(initializers)) + "> stock_anatomy_table{{\n")
    lines.append(",\n".join(initializers))
    lines.append("\n}};\n")
    result: str = "".join(lines)
    return result


def main(argv: Sequence[str] | None = None) -> int:
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed table is stale")
    arguments: argparse.Namespace = parser.parse_args(argv)
    schema: Mapping[str, object] = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    table: str = render(schema)
    if arguments.check:
        current: str = TABLE_PATH.read_text(encoding="utf-8") if TABLE_PATH.exists() else ""
        if current != table:
            print("stock anatomies: " + str(TABLE_PATH) + " is stale; run tools/stock_anatomies.py")
            return 1
        print("stock anatomies: " + str(TABLE_PATH) + " is current")
        return 0
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    TABLE_PATH.write_text(table, encoding="utf-8", newline="\n")
    print("stock anatomies: wrote " + str(TABLE_PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main())
