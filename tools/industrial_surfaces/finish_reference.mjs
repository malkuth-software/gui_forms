// The byte reference for the engine's finish kernel
// (src/core/engine/primitives/finish/finish_kernel.cpp): runs the
// JavaScript kernels in finish_kernel.js beside this file.
//
//   node tools/industrial_surfaces/finish_reference.mjs tables <file>
//       writes finish_tables.inc: the sRGB-to-linear table (float32, as the
//       reference stores it), the 4097-step linear-to-sRGB table, and the
//       cosine and sine of every whole degree as the reference computes them
//       (Math.cos(d * Math.PI / 180)), so the kernel calls no libm function.
//   node tools/industrial_surfaces/finish_reference.mjs hashes
//       prints, for each case of tests/engine_finish_tests.cpp, the FNV-1a
//       64 hash of the reference's pixels in RGBA order; the test checks the
//       kernel's bytes against them.
//   node tools/industrial_surfaces/finish_reference.mjs bytes <dir>
//       writes each case's pixels as raw RGBA (<case>.rgba), for a byte by
//       byte comparison when a hash differs.
//
// The cases must match finish_cases in tests/engine_finish_tests.cpp.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const context = vm.createContext({ Math, Float32Array, Uint8Array, Uint8ClampedArray, parseInt });
vm.runInContext(fs.readFileSync(path.join(here, 'finish_kernel.js'), 'utf8') + '\nthis.Finish = Finish;', context);
const { Finish } = context;

// name, finish, scale, logical width and height, seed, paint, second colour, grain
const cases = [];
const kinds = ['dusty_matte', 'orange_peel', 'hammertone', 'wrinkle', 'bead_blast', 'sand_cast', 'flat_baseline', 'cloth_weave'];
for (const kind of kinds) {
  for (const scale of [1, 2, 3]) {
    const second = kind === 'cloth_weave' ? '#c8b98f' : '#bdb6a8';
    cases.push({ name: `${kind}_${scale}`, finish: kind, k: scale, w: 48, h: 32, seed: 7, colour: '#2f6e6c', dust: second, grain: 1 });
  }
}
cases.push({ name: 'orange_peel_grain_2', finish: 'orange_peel', k: 2, w: 48, h: 32, seed: 7, colour: '#2f6e6c', dust: '#bdb6a8', grain: 2 });
cases.push({ name: 'hammertone_seed_11', finish: 'hammertone', k: 2, w: 48, h: 32, seed: 11, colour: '#4d676d', dust: '#bdb6a8', grain: 1 });

function render(c) {
  const W = c.w * c.k, H = c.h * c.k;
  const img = { data: new Uint8ClampedArray(W * H * 4), width: W };
  Finish.paint(img, { x: 0, y: 0, w: W, h: H }, { x: 0, y: 0, w: W, h: H }, {
    finish: c.finish, k: c.k, seed: c.seed, colour: c.colour, dustColour: c.dust, grain: c.grain,
    light: Finish.lightOf(125, 38), ambient: 0.32,
  });
  return img.data;
}

function fnv(bytes) {
  let hash = 14695981039346656037n;
  const prime = 1099511628211n;
  const mask = (1n << 64n) - 1n;
  for (let i = 0; i < bytes.length; i++) {
    hash ^= BigInt(bytes[i]);
    hash = (hash * prime) & mask;
  }
  return hash;
}

function floatLiteral(v) {
  // The shortest decimal that reads back as this float32.
  for (let digits = 1; digits <= 9; digits++) {
    const text = v.toPrecision(digits);
    if (Math.fround(Number(text)) === v) return text.includes('e') || text.includes('.') ? text + 'F' : text + '.0F';
  }
  return v.toPrecision(9) + 'F';
}

function doubleLiteral(v) {
  const text = String(v);
  return text.includes('e') || text.includes('.') ? text : text + '.0';
}

const mode = process.argv[2];
if (mode === 'tables') {
  const lines = [];
  lines.push('// Generated by tools/industrial_surfaces/finish_reference.mjs tables; do not edit.');
  lines.push('// The reference kernels\' tables (finish_kernel.js), so that the engine\'s');
  lines.push('// kernel calls no libm function and matches the reference byte for byte.');
  lines.push('');
  lines.push('// sRGB byte to linear light, stored as float as the reference stores it.');
  lines.push('inline constexpr std::array<float, 256> finish_linear_table{{');
  for (let i = 0; i < 256; i += 8) {
    const row = [];
    for (let j = i; j < i + 8; j++) row.push(floatLiteral(Finish.TO_LINEAR[j]));
    lines.push('    ' + row.join(', ') + ',');
  }
  lines.push('}};');
  lines.push('');
  lines.push('// Linear light in [0, 1] to an sRGB byte, in 4096 steps: entry i is the');
  lines.push('// byte for i / 4096.');
  lines.push('inline constexpr std::array<std::uint8_t, 4097> finish_encode_table{{');
  for (let i = 0; i <= 4096; i += 16) {
    const row = [];
    for (let j = i; j < Math.min(i + 16, 4097); j++) row.push(String(Finish.encode(j / 4096)) + 'U');
    lines.push('    ' + row.join(', ') + ',');
  }
  lines.push('}};');
  lines.push('');
  lines.push('// The cosine and sine of each whole degree from 0 to 359, as the reference');
  lines.push('// computes them: Math.cos(d * Math.PI / 180).');
  for (const [name, fn] of [['finish_degree_cosines', Math.cos], ['finish_degree_sines', Math.sin]]) {
    lines.push(`inline constexpr std::array<double, 360> ${name}{{`);
    for (let d = 0; d < 360; d += 4) {
      const row = [];
      for (let j = d; j < d + 4; j++) row.push(doubleLiteral(fn(j * Math.PI / 180)));
      lines.push('    ' + row.join(', ') + ',');
    }
    lines.push('}};');
    lines.push('');
  }
  fs.writeFileSync(process.argv[3], lines.join('\n'));
} else if (mode === 'hashes') {
  for (const c of cases) console.log(`${c.name} 0x${fnv(render(c)).toString(16)}ULL`);
} else if (mode === 'bytes') {
  fs.mkdirSync(process.argv[3], { recursive: true });
  for (const c of cases) fs.writeFileSync(path.join(process.argv[3], `${c.name}.rgba`), render(c));
} else {
  console.error('usage: finish_reference.mjs tables <file> | hashes | bytes <dir>');
  process.exit(2);
}
