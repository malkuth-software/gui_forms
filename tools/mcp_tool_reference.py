#!/usr/bin/env python3
"""The MCP tool reference: the built-in tools as a program serves them.

    python3 tools/mcp_tool_reference.py --program <built GUI.Forms program>
    python3 tools/mcp_tool_reference.py --check [--program <program>]

With --program, starts the program with --mcp (it needs a window server),
asks it for tools/list, keeps the built-in tools (those whose names have no
dot: a program's own tools are named <program>.<tool>) and writes them to
manifests/mcp_tools.json, then renders docs/user/mcp-tools.md from that
file. Use a program that registers no tools of its own, or its tools are
left out anyway.

--check renders the page from the committed manifests/mcp_tools.json and
fails when docs/user/mcp-tools.md differs; with --program it also fails when
the program serves a different list than the committed one. The first needs
no build and no window server, so the docs checks run it everywhere; the
second runs where a build is (MCP round 1: the reference is generated, never
written by hand).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import check_mcp_launch  # noqa: E402

MANIFEST = ROOT / 'manifests' / 'mcp_tools.json'
PAGE = ROOT / 'docs' / 'user' / 'mcp-tools.md'


def fetch(program: Path, timeout: float) -> list[dict]:
    """The built-in tools `program` lists, in its order."""
    exchange = check_mcp_launch.Exchange(program, None)
    try:
        reply = exchange.request(1, 'initialize', {
            'protocolVersion': check_mcp_launch.PROTOCOL_VERSION, 'capabilities': {},
            'clientInfo': {'name': 'gui-forms-mcp-tool-reference', 'version': '1'}}, timeout)
        if reply is None or 'result' not in reply:
            raise RuntimeError('no answer to initialize: ' + ' | '.join(exchange.errors))
        exchange.send({'jsonrpc': '2.0', 'method': 'notifications/initialized'})
        listed = exchange.request(2, 'tools/list', {}, timeout)
        tools = ((listed or {}).get('result') or {}).get('tools') or []
    finally:
        exchange.close(timeout)
    unbound = [line for line in exchange.errors if 'could not be bound' in line]
    if unbound:
        # A schema outside the MCP server's subset leaves its tool unserved.
        raise RuntimeError('; '.join(unbound))
    if not tools:
        raise RuntimeError('the program listed no tools')
    built_in = [tool for tool in tools if '.' not in tool.get('name', '')]
    return built_in


def type_text(schema: dict) -> str:
    """A property's type as the page shows it."""
    if 'enum' in schema:
        return 'one of ' + ', '.join('`' + str(value) + '`' for value in schema['enum'])
    kind = schema.get('type')
    if kind == 'array':
        items = schema.get('items') or {}
        inner = type_text(items) if items else 'any'
        return 'array of ' + inner
    if isinstance(kind, list):
        return ' or '.join(str(part) for part in kind)
    if kind:
        return str(kind)
    if 'anyOf' in schema or 'oneOf' in schema:
        return 'one of several shapes'
    return 'any'


def cell(text: str) -> str:
    """Text fit for one table cell."""
    flattened = ' '.join(text.split())
    escaped = flattened.replace('|', '\\|')
    return escaped


def render(tools: list[dict]) -> str:
    lines: list[str] = [
        '# MCP tools',
        '',
        '<!-- Generated by tools/mcp_tool_reference.py from manifests/mcp_tools.json; do not edit. -->',
        '',
        'The tools every GUI.Forms program serves under `--mcp` '
        '([hosts and capabilities](hosts-and-capabilities.md)), as a built program lists them. '
        "A program adds its own beside them with `register_model_tool`; those are named "
        '`<program>.<tool>` and are not listed here. Every tool refuses an argument its schema does not name.',
        '',
    ]
    for tool in tools:
        name = tool.get('name', '')
        lines.append('## `' + name + '`')
        lines.append('')
        title = tool.get('title') or (tool.get('annotations') or {}).get('title')
        if title:
            lines.append('**' + str(title) + '.** ' + ' '.join(str(tool.get('description', '')).split()))
        else:
            lines.append(' '.join(str(tool.get('description', '')).split()))
        lines.append('')
        schema = tool.get('inputSchema') or {}
        properties = schema.get('properties') or {}
        required = set(schema.get('required') or [])
        if not properties:
            lines.append('No arguments.')
            lines.append('')
            continue
        lines.append('| Argument | Type | Required | Meaning |')
        lines.append('|---|---|---|---|')
        for argument, member in properties.items():
            meaning = cell(str(member.get('description', '')))
            lines.append('| `' + argument + '` | ' + cell(type_text(member)) + ' | ' +
                         ('yes' if argument in required else 'no') + ' | ' + meaning + ' |')
        lines.append('')
    text = '\n'.join(lines)
    return text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--program', type=Path)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--timeout', type=float, default=60.0)
    arguments = parser.parse_args(argv)
    if not arguments.check and arguments.program is None:
        parser.error('name a --program to generate from, or --check')
    fetched: list[dict] | None = None
    if arguments.program is not None:
        try:
            fetched = fetch(arguments.program.resolve(), arguments.timeout)
        except RuntimeError as error:
            print(f'mcp_tool_reference: {error}', file=sys.stderr)
            return 1
    if arguments.check:
        committed = json.loads(MANIFEST.read_text(encoding='utf-8'))
        problems: list[str] = []
        if fetched is not None and fetched != committed:
            problems.append('the program serves a different tool list than manifests/mcp_tools.json')
        if not PAGE.is_file() or PAGE.read_text(encoding='utf-8') != render(committed):
            problems.append('docs/user/mcp-tools.md is stale')
        for problem in problems:
            print(f'mcp_tool_reference: {problem}; run python3 tools/mcp_tool_reference.py --program <program>',
                  file=sys.stderr)
        return 1 if problems else 0
    MANIFEST.write_text(json.dumps(fetched, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    PAGE.write_text(render(fetched), encoding='utf-8')
    print(f'mcp_tool_reference: {len(fetched)} tools -> {PAGE.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
