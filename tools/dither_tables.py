#!/usr/bin/env python3
"""Writes the engine's blue-noise dither table (gradient dithering).

The material kernel dithers its final quantisation to 8 bits with a
threshold per device pixel (src/core/engine/primitives/kernel/dither.hpp).
The ordered mode's 8 x 8 Bayer ranks are generated by the kernel itself; the
blue-noise mode's 64 x 64 ranks come from this script, which writes them to
src/core/engine/primitives/kernel/blue_noise_ranks.inc.

The ranks are made by Ulichney's void-and-cluster method on a 64 x 64 torus
in integers only, so the table is the same on every host and every Python:

- the energy filter is the outer product of the binomial row
  1 8 28 56 70 56 28 8 1 (a Gaussian of variance 2, sigma about 1.41),
  over the 9 x 9 neighbourhood, wrapped at the torus' edges;
- the starting pattern is 410 points (10 %) drawn by a 32-bit xorshift
  from a fixed seed, then relaxed by moving the tightest cluster's point
  to the largest void until the two coincide;
- phase 1 ranks the starting points by removing the tightest cluster
  repeatedly (ranks 409 down to 0); phase 2 ranks the rest by filling the
  largest void repeatedly (ranks 410 up to 4095). Filling the largest void
  of the points is filling the tightest cluster of the gaps, since every
  cell's energy over points and gaps together is the filter's sum, so
  Ulichney's third phase is the second continued.

Ties go to the lowest cell index (row-major). Usage:

    python3 -B tools/dither_tables.py           # write the table
    python3 -B tools/dither_tables.py --check   # fail when it is stale
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "core" / "engine" / "primitives" / "kernel" / "blue_noise_ranks.inc"

SIDE = 64
CELLS = SIDE * SIDE
BINOMIAL = (1, 8, 28, 56, 70, 56, 28, 8, 1)
REACH = len(BINOMIAL) // 2
STARTING_POINTS = 410
SEED = 0x9E3779B9
# Larger than any cell's energy (70 * 70 * 81 < 2^20).
BEYOND = 1 << 40


def xorshift32(state: int) -> int:
    state ^= (state << 13) & 0xFFFFFFFF
    state ^= state >> 17
    state ^= (state << 5) & 0xFFFFFFFF
    return state & 0xFFFFFFFF


def neighbourhood() -> list[tuple[int, int, int]]:
    """The filter as (dx, dy, weight), the centre left out."""
    cells = []
    for dy in range(-REACH, REACH + 1):
        for dx in range(-REACH, REACH + 1):
            if dx == 0 and dy == 0:
                continue
            cells.append((dx, dy, BINOMIAL[dx + REACH] * BINOMIAL[dy + REACH]))
    return cells


class Pattern:
    """Points on the torus, each cell's energy from the points around it,
    and two views for the searches: the gaps' energies (points read as
    BEYOND) and the points' energies (gaps read as -1)."""

    def __init__(self) -> None:
        self.filled = [False] * CELLS
        self.energy = [0] * CELLS
        self.gaps = [0] * CELLS
        self.points = [-1] * CELLS
        self.filter = neighbourhood()

    def _views(self, cell: int) -> None:
        if self.filled[cell]:
            self.gaps[cell] = BEYOND
            self.points[cell] = self.energy[cell]
        else:
            self.gaps[cell] = self.energy[cell]
            self.points[cell] = -1

    def _spread(self, cell: int, sign: int) -> None:
        x = cell % SIDE
        y = cell // SIDE
        for dx, dy, weight in self.filter:
            near = ((y + dy) % SIDE) * SIDE + (x + dx) % SIDE
            self.energy[near] += sign * weight
            self._views(near)

    def add(self, cell: int) -> None:
        self.filled[cell] = True
        self._views(cell)
        self._spread(cell, 1)

    def remove(self, cell: int) -> None:
        self.filled[cell] = False
        self._views(cell)
        self._spread(cell, -1)

    def tightest_cluster(self) -> int:
        return self.points.index(max(self.points))

    def largest_void(self) -> int:
        return self.gaps.index(min(self.gaps))


def starting_cells() -> list[int]:
    cells: list[int] = []
    taken = [False] * CELLS
    state = SEED
    while len(cells) < STARTING_POINTS:
        state = xorshift32(state)
        cell = state % CELLS
        if taken[cell]:
            continue
        taken[cell] = True
        cells.append(cell)
    return cells


def relaxed_start() -> list[int]:
    pattern = Pattern()
    for cell in starting_cells():
        pattern.add(cell)
    while True:
        cluster = pattern.tightest_cluster()
        pattern.remove(cluster)
        void = pattern.largest_void()
        pattern.add(void)
        if void == cluster:
            break
    return [cell for cell in range(CELLS) if pattern.filled[cell]]


def blue_noise_ranks() -> list[int]:
    start = relaxed_start()
    ranks = [-1] * CELLS
    pattern = Pattern()
    for cell in start:
        pattern.add(cell)
    for rank in range(len(start) - 1, -1, -1):
        cluster = pattern.tightest_cluster()
        pattern.remove(cluster)
        ranks[cluster] = rank
    pattern = Pattern()
    for cell in start:
        pattern.add(cell)
    for rank in range(len(start), CELLS):
        void = pattern.largest_void()
        pattern.add(void)
        ranks[void] = rank
    if sorted(ranks) != list(range(CELLS)):
        raise SystemExit("dither_tables: the ranks are not a permutation")
    return ranks


def table_text(ranks: list[int]) -> str:
    lines = [
        "// Generated by tools/dither_tables.py; do not edit.",
        "// The blue-noise dither's ranks (dither.hpp): 64 x 64, row-major, each of",
        "// 0 to 4095 once, by void-and-cluster in integers (see the generator).",
        "",
        "inline constexpr std::array<std::uint16_t, 4096> blue_noise_rank_table{{",
    ]
    for row in range(SIDE):
        values = ranks[row * SIDE:(row + 1) * SIDE]
        for half in range(0, SIDE, 16):
            lines.append("    " + " ".join("%d," % value for value in values[half:half + 16]))
    lines.append("}};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the checked-in table is stale")
    arguments = parser.parse_args()
    text = table_text(blue_noise_ranks())
    if arguments.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("dither_tables: %s is stale; run tools/dither_tables.py" % OUTPUT.relative_to(ROOT))
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
