// DataGridView's property capabilities (property-capabilities study, sections
// 2, 14 and 15). Generated by tools/property_codemod.py from
// tools/property_families/data_grid_view.json: edit the config, not this file.
//
// Each is a standard-layout struct whose only member is its property's
// cell, taken by the declaring class as a base. A write
// `(*control).x = value;` runs `assign`: the declaring class's
// prepare_write hook (require_mutable first, then the value's checks and,
// where C# lets a subclass rewrite the value, the protected virtual coerce
// hook), the compare and store, then the written hook (the touch, side
// effects and the change event, through the protected virtual
// on_<property>_changed() where Windows Forms has OnXChanged). A read is
// `(*control).x.read()`.

// How columns size themselves (AutoSizeColumnsMode).
template <typename Declaring>
struct DataGridViewAutoSizeColumnsModeCapability {
    PropertyCell<DataGridViewAutoSizeColumnsMode, DataGridViewAutoSizeColumnsModeCapability<Declaring>> auto_size_columns_mode{DataGridViewAutoSizeColumnsMode::none};

    static void assign(DataGridViewAutoSizeColumnsModeCapability& capability, DataGridViewAutoSizeColumnsMode incoming) {
        Declaring& control = static_cast<Declaring&>(capability);
        control.prepare_write(std::as_const(capability.auto_size_columns_mode), incoming);
        if (!capability.auto_size_columns_mode.replace(std::move(incoming))) return;
        control.written(std::as_const(capability.auto_size_columns_mode));
    }
};

