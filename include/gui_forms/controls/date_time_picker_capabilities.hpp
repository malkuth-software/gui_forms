// Whether the calendar is open; a view, since the calendar closes itself on commit, cancel and dismissal. A write opens or closes it and raises drop_down_changed.
template <typename Declaring>
struct DateTimePickerDroppedDownCapability {
    PropertyView<bool, DateTimePickerDroppedDownCapability<Declaring>> dropped_down;

    static void assign(DateTimePickerDroppedDownCapability& capability, bool incoming) {
        Declaring& control = static_cast<Declaring&>(capability);
        control.write_view(std::as_const(capability.dropped_down), std::move(incoming));
    }

    static bool read(const DateTimePickerDroppedDownCapability& capability) {
        const Declaring& control = static_cast<const Declaring&>(capability);
        bool current = control.read_view(capability.dropped_down);
        return current;
    }
};

