// DateTimePicker's property capabilities (property-capabilities study, sections
// 2, 14 and 15). Generated by tools/property_codemod.py from
// tools/property_families/date_time_picker.json: edit the config, not this file.
//
// Each is a standard-layout struct whose only member is its property's
// cell, taken by the declaring class as a base. A write
// `(*control).x = value;` runs `assign`: the declaring class's
// prepare_write hook (require_mutable first, then the value's checks), the
// compare and store, then the written hook (the touch, side effects and the
// change event, through the protected virtual on_<property>_changed() where
// Windows Forms has an overridable On<Property>Changed; other properties
// have no hook, and a subclass subscribes to their change events instead). A read is
// `(*control).x.read()`.

// The shown date and time (Value), within minimum and maximum; an invalid or out-of-range value throws std::out_of_range. A change raises value_changed.
template <typename Declaring>
struct DateTimePickerValueCapability {
    PropertyCell<DateTimeValue, DateTimePickerValueCapability<Declaring>> value{DateTimeValue{2000, 1U, 1U}};

    static void assign(DateTimePickerValueCapability& capability, DateTimeValue incoming) {
        Declaring& control = static_cast<Declaring&>(capability);
        control.prepare_write(std::as_const(capability.value), incoming);
        if (!capability.value.replace(std::move(incoming))) return;
        control.written(std::as_const(capability.value));
    }
};

