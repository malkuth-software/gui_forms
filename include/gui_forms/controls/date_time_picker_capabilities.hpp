// Every DateTimePicker capability, in the order the declaring class takes them.
template <typename Declaring>
struct DateTimePickerCapabilities : public DateTimePickerValueCapability<Declaring>,
                                    public DateTimePickerMinimumCapability<Declaring>,
                                    public DateTimePickerMaximumCapability<Declaring>,
                                    public DateTimePickerFormatPropertyCapability<Declaring>,
                                    public DateTimePickerCustomFormatCapability<Declaring>,
                                    public DateTimePickerFormatProviderCapability<Declaring>,
                                    public DateTimePickerShowCheckBoxCapability<Declaring>,
                                    public DateTimePickerCheckedCapability<Declaring>,
                                    public DateTimePickerShowUpDownCapability<Declaring>,
                                    public DateTimePickerDroppedDownCapability<Declaring>,
                                    public DateTimePickerDropDownAlignmentCapability<Declaring>,
                                    public FontCapability<Declaring>,
                                    public DateTimePickerStyleCapability<Declaring> {
    DateTimePickerCapabilities() : FontCapability<Declaring>(FontSpec{FontRole::content, 12.0, 400, false}) {}
};

